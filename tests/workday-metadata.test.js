import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { workdayMetadata } from '../server/workday-metadata.js';
import { openStore } from '../server/db.js';
import { createEnricher } from '../server/enrichment.js';
import { fetchJobDescription } from '../server/detail-fetch.js';
const full = 'Build and test software with Python. Collaborate with engineers and learn new technical skills. '.repeat(6);
const url = 'https://example.wd1.myworkdayjobs.com/External/job/US/Intern_JR123';
const detail = { jobDescription: full, startDate: '2026-10-20', postedOn: 'Posted 7 Days Ago', timeType: 'Full time', remoteType: 'Hybrid', jobReqId: 'JR123', location: 'Boston, MA', additionalLocations: ['New York, NY'] };
test('Workday distinguishes exact, relative, and lower-bound dates and extracts job facts', () => {
  const exact = workdayMetadata(detail, { detail: true });
  assert.equal(exact.postedAt, '2026-10-20T00:00:00.000Z'); assert.equal(exact.dateBasis, 'published');
  assert.equal(exact.postingMetadata.workplaceType, 'Hybrid'); assert.equal(exact.postingMetadata.timeType, 'Full time');
  assert.deepEqual(exact.postingMetadata.locations, ['Boston, MA','New York, NY']);
  const relative = workdayMetadata({ postedOn: 'Posted 4 Days Ago', bulletFields: ['JR123'] }, { now: Date.parse('2026-10-27') });
  assert.equal(relative.postedAt, '2026-10-23T00:00:00.000Z'); assert.equal(relative.dateBasis, 'estimated');
  assert.equal(relative.postingMetadata.requisitionId, 'JR123');
  assert.equal(workdayMetadata({ postedOn: 'Posted 30+ Days Ago' }).postedAt, null);
  assert.equal(workdayMetadata({ location: 'Boston' }, { detail: true }).postingMetadata.workplaceType, undefined);
});
test('full Workday descriptions still backfill metadata, preserve notes and survive later lightweight refreshes', async t => {
  const dir = mkdtempSync(join(tmpdir(), 'workday-facts-')), store = openStore(dir);
  const source = store.sources().find(s => s.kind === 'workday');
  const job = { title: 'Software Intern', company: 'Example', url, location: '2 Locations', description: full };
  store.ingest(source, [job]);
  const initial = store.jobs()[0];
  store.db.prepare('INSERT INTO applications VALUES (?,?,?,?)').run(initial.id, 'saved', null, 'Keep this note');
  const enricher = createEnricher(store, { resolver: item => fetchJobDescription(item, [], { request: async () => ({ body: JSON.stringify({ jobPostingInfo: detail }) }) }), hostDelayMs: 0 });
  t.after(() => { enricher.stop(); store.close(); rmSync(dir, { recursive: true, force: true }); });
  enricher.sync(); assert.equal(enricher.jobStatus(initial.id).state, 'pending');
  await enricher.run();
  let updated = store.job(initial.id);
  assert.equal(updated.workplaceType, 'Hybrid'); assert.equal(updated.remote, false);
  assert.equal(updated.postedAt, '2026-10-20T00:00:00.000Z'); assert.equal(updated.requisitionId, 'JR123');
  assert.equal(updated.location, 'Boston, MA · New York, NY'); assert.equal(updated.note, 'Keep this note');
  store.ingest(source, [{ ...job, description: '', ...workdayMetadata({ locationsText: '2 Locations', postedOn: 'Posted Today' }) }]);
  updated = store.job(initial.id);
  assert.equal(updated.postedAt, '2026-10-20T00:00:00.000Z'); assert.equal(updated.location, 'Boston, MA · New York, NY');
  assert.equal(updated.timeType, 'Full time'); assert.equal(updated.firstSeen, initial.firstSeen);
  enricher.sync(); assert.equal(enricher.jobStatus(initial.id).state, 'done');
});

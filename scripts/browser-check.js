import { chromium } from '@playwright/test';
import { mkdtempSync, rmSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import assert from 'node:assert/strict';
import { createApp } from '../server/index.js';
import { openStore } from '../server/db.js';

const directory = mkdtempSync(join(tmpdir(), 'internscope-browser-'));
const store = openStore(directory);
const jobs = [
  { title: 'Software Engineering Intern — Summer 2027', company: 'Acme', location: 'Los Angeles, California', url: 'https://example.com/software', description: 'Build useful software with Python, React, TypeScript, SQL, Git and AWS. Collaborate with engineering and design teams on thoughtful user experiences. Gain hands-on experience building and testing reliable data pipelines. This paid internship is open to undergraduate students studying computer science.', terms: ['summer'], years: ['2027'] },
  { title: 'Robotics Intern — Summer 2027', company: 'Orbit Labs', location: 'San Francisco, California', url: 'https://example.com/robotics', description: 'Develop embedded firmware with Python and C++. Design experiments using robotics, MATLAB, and embedded systems. Work with our mechanical engineering team to test autonomous systems for a new generation of machines.', terms: ['summer'], years: ['2027'] },
  { title: 'Finance Intern — Fall 2027', company: 'Fieldwork', location: 'New York, NY', url: 'https://example.com/finance', description: 'Use Excel and financial modeling to support finance and accounting projects. Learn valuation and research.', terms: ['fall'], years: ['2027'] }
];
store.ingest(store.sources()[0], jobs);
store.ingest(store.sources().find(source => source.kind === 'runway'), [jobs[0]]);
store.ingest(store.sources().find(source => source.kind === 'internlist'), [jobs[1]]);
store.ingest(store.sources().find(source => source.kind === 'workday'), [jobs[0]]);
const { app, refresher } = createApp({ store, collector: async () => jobs, enrich: async rows => rows });
const server = app.listen(0, '127.0.0.1');
await new Promise(resolve => server.on('listening', resolve));
let browser;
try {
  browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.locator('.job-card').first().waitFor();
  assert.equal(await page.locator('.job-card').count(), 3);
  await page.locator('#hero-button').click();
  await page.getByRole('tab', { name: 'Paste text or source' }).click();
  await page.locator('#resume-text').fill('Software engineering student with Python, React, TypeScript, SQL, Git, AWS and C++ experience. Built reliable data pipelines and embedded robotics projects.');
  await page.locator('#resume-submit').click();
  await page.locator('#modal').waitFor({ state: 'hidden' });
  await page.locator('.score:not(.empty)').first().waitFor();
  assert.equal(await page.locator('.score.empty').count(), 0);
  await page.locator('.nav-item[data-open="preferences"]').click();
  await page.locator('input[name="locations"]').fill('California');
  await page.locator('select[name="season"]').selectOption('summer');
  await page.locator('input[name="year"]').fill('2027');
  await page.locator('input[name="includeUnknown"]').uncheck();
  await page.getByRole('button', { name: 'Save preferences' }).click();
  await page.locator('#modal').waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.querySelectorAll('.job-card').length === 2);
  const firstId = await page.locator('.job-card').first().getAttribute('data-job');
  await page.locator('.job-card').first().getByRole('button', { name: /^Save / }).click();
  await page.waitForFunction(() => document.querySelector('#nav-saved').textContent === '1');
  await page.locator('.nav-item[data-view="saved"]').click();
  await page.waitForFunction(() => document.querySelectorAll('.job-card').length === 1);
  await page.locator('.job-card').getByRole('button', { name: 'Applied', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#nav-applied').textContent === '1');
  await page.locator('.nav-item[data-view="applied"]').click();
  await page.waitForFunction(() => document.querySelectorAll('.job-card').length === 1);
  await page.locator('.job-card').getByRole('button', { name: 'View job' }).click();
  await page.locator('#job-note').fill('Applied today. Ask about the robotics team.');
  await page.locator('#save-note').click();
  await page.waitForFunction(() => document.querySelector('#toast-message').textContent === 'Notes saved.');
  await page.locator('#close-modal').click();
  await page.reload();
  await page.locator('.job-card').first().waitFor();
  assert.equal(await page.locator(`.job-card[data-job="${firstId}"]`).count(), 0);
  await page.locator('.nav-item[data-view="applied"]').click();
  await page.locator('.job-card').first().waitFor();
  await page.locator('.job-card').getByRole('button', { name: 'View job' }).click();
  assert.match(await page.locator('#job-note').inputValue(), /Applied today/);
  await page.locator('#close-modal').click();
  await page.locator('.job-card').getByRole('button', { name: 'Restore', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#nav-applied').textContent === '0');
  await page.locator('.nav-item[data-view="new"]').click();
  await page.waitForFunction(() => document.querySelectorAll('.job-card').length === 2);
  await page.locator('.job-card').first().getByRole('button', { name: 'Applied', exact: true }).click();
  await page.locator('#toast-undo').click();
  await page.waitForFunction(() => document.querySelectorAll('.job-card').length === 2);
  await page.locator('.nav-item[data-open="resume"]').click();
  await page.locator('#resume-file').setInputFiles({ name: 'resume.txt', mimeType: 'text/plain', buffer: Buffer.from('Software engineering student building Python React SQL and TypeScript applications with Git and AWS.') });
  await page.locator('#resume-submit').click();
  await page.locator('#modal').waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.querySelector('#resume-description').textContent.includes('resume.txt'));
  await page.locator('.nav-item[data-open="sources"]').click();
  await page.locator('input[name="name"]').fill('Test Company');
  await page.locator('input[name="token"]').fill('test-company');
  await page.getByRole('button', { name: 'Connect source' }).click();
  await page.getByText('Test Company', { exact: true }).waitFor();
  await page.locator('#close-modal').click();
  await page.locator('#platform-filter').selectOption('linkedin');
  await page.waitForFunction(() => document.querySelectorAll('.job-card').length === 0);
  await page.locator('#platform-filter').selectOption('');
  await page.waitForFunction(() => document.querySelectorAll('.job-card').length === 2);
  await page.locator('#platform-filter').selectOption('runway');
  await page.waitForFunction(() => document.querySelectorAll('.job-card').length === 1);
  assert.match(await page.locator('.job-card').textContent(), /Acme/);
  await page.locator('#platform-filter').selectOption('workday');
  await page.waitForFunction(() => document.querySelectorAll('.job-card').length === 1);
  assert.match(await page.locator('.job-card').textContent(), /Acme/);
  await page.locator('#platform-filter').selectOption('internlist');
  await page.waitForFunction(() => document.querySelectorAll('.job-card').length === 1);
  assert.match(await page.locator('.job-card').textContent(), /Orbit Labs/);
  await page.locator('#platform-filter').selectOption('');
  await page.waitForFunction(() => document.querySelectorAll('.job-card').length === 2);
  await page.locator('.nav-item[data-open="sources"]').click();
  assert.equal(await page.locator('.coverage-card').count(), 9);
  assert.match(await page.locator('.coverage-grid').textContent(), /Workday/);
  assert.match(await page.locator('.coverage-grid').textContent(), /Lever/);
  await page.locator('#source-form select[name="kind"]').selectOption('workday');
  await page.locator('#source-form input[name="name"]').fill('Workday Test');
  await page.locator('#source-form input[name="token"]').fill('https://example.wd5.myworkdayjobs.com/en-US/External');
  await page.getByRole('button', { name: 'Connect source' }).click();
  await page.getByText('Workday Test', { exact: true }).waitFor();
  await page.locator('#serpapi-key').fill('test-only-local-key-1234567890');
  await page.getByRole('button', { name: 'Save key', exact: true }).click();
  await page.locator('#disconnect-index').waitFor();
  assert.equal(await page.locator('#serpapi-key').inputValue(), '');
  await page.locator('#disconnect-index').click();
  await page.waitForFunction(() => !document.querySelector('#disconnect-index'));
  await page.locator('#source-search').fill('Test Company');
  assert.equal(await page.locator('#source-list .source-row:visible').count(), 1);
  await page.locator('#source-search').fill('');
  await page.locator('#source-kind-filter').selectOption('linkedin');
  assert.equal(await page.locator('#source-list .source-row:visible').count(), 1);
  await page.locator('#source-kind-filter').selectOption('workday');
  assert.equal(await page.locator('#source-list .source-row:visible').count(), 5);
  await page.locator('#source-kind-filter').selectOption('');
  mkdirSync('test-results', { recursive: true });
  await page.locator('#modal').evaluate(el => { el.scrollTop = 0; });
  await page.screenshot({ path: 'test-results/sources-desktop.png', animations: 'disabled' });
  await page.locator('#close-modal').click();
  mkdirSync('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile layout must not overflow');
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true, animations: 'disabled' });
  await page.locator('#mobile-menu').click();
  await page.locator('.nav-item[data-open="preferences"]').click();
  assert.ok(await page.locator('#modal').isVisible());
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.locator('#close-modal').click();
  await page.locator('.nav-item[data-open="sources"]').click();
  assert.ok(await page.locator('#modal').evaluate(el => el.scrollWidth <= el.clientWidth), 'Mobile source controls must fit the dialog');
  await page.screenshot({ path: 'test-results/sources-mobile.png', animations: 'disabled' });
  await page.locator('#close-modal').click();
  assert.deepEqual(errors, []);
  console.log('Browser workflow passed: resume paste/upload, filters, save, apply, undo, restore, persistence, notes, source coverage/filtering, private API key save/clear, mobile layout, no client errors.');
} finally {
  await browser?.close(); refresher.stop();
  await new Promise(resolve => server.close(resolve));
  store.close(); rmSync(directory, { recursive: true, force: true });
}
